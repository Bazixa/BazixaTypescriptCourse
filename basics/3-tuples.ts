// we can create a tuple in typescript, which is an array with fixed number of elements and types
let user: [string, number, boolean] = ['Kemal', 30, true];
// that's mean we can create a tuple with 3 elements, first element is string, second element is number and third element is boolean

user = ['Bazixa', 25, false]; // we can change the values of the tuple, but we can't change the types of the elements
